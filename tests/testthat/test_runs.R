test_that("collection rejects missing, failed and nonfinite jobs", {
  source(file.path(root, "R", "runs.R"), local = TRUE)
  directory <- tempfile()
  dir.create(directory)
  on.exit(unlink(directory, recursive = TRUE))
  input <- file.path(directory, "input.txt")
  writeLines("configuration", input)
  paths <- file.path(directory, c("one.rds", "two.rds"))
  register_run(directory, paths, inputs = input)
  expect_error(read_run(directory), "2 missing jobs")
  save_job(paths[1], data.frame(pred = 1))
  expect_error(read_run(directory), "1 missing jobs")
  save_job(paths[2], stop("deliberate solver failure"))
  expect_match(readRDS(paths[2])$error, "solver failure")
  expect_error(read_run(directory), "failed jobs: two.rds")
  save_job(paths[2], data.frame(pred = NA_real_))
  expect_error(read_run(directory), "failed jobs: two.rds")
  save_job(paths[2], data.frame(att = NA_real_, se = NA_real_))
  expect_error(read_run(directory), "failed jobs: two.rds")
  save_job(paths[2], data.frame(pred = 2))
  expect_equal(length(read_run(directory)), 2)
  expect_silent(register_run(directory, paths, inputs = input))
  expect_error(register_run(directory, paths, inputs = input,
                            runtime = list(R = "different version")),
               "inputs changed")
  writeLines("different configuration", input)
  expect_error(register_run(directory, paths, inputs = input), "inputs changed")
})

test_that("unidentified checkpoints cannot be adopted into a new run", {
  source(file.path(root, "R", "runs.R"), local = TRUE)
  directory <- tempfile()
  dir.create(directory)
  on.exit(unlink(directory, recursive = TRUE))
  path <- file.path(directory, "one.rds")
  saveRDS(data.frame(pred = 1), path)
  expect_error(register_run(directory, path, inputs = path), "no manifest")
  expect_error(read_run(directory), "manifest is missing")
})
